#!/usr/bin/env python3
"""Generate paper/jar/main.tex (Springer Nature sn-jnl, for the Journal of Automated
Reasoning) from the LIPIcs source paper/main.tex.

Only the class, front matter, theorem environments, back matter and bibliography setup are
replaced. Every line of the body (from the Introduction to the end of the appendices) is copied
unchanged, apart from the two structural edits listed in FIDELITY.md. Run from any directory:

    python3 paper/jar/port.py

The script fails loudly if paper/main.tex no longer has the structure it expects.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "main.tex"
OUT = HERE / "main.tex"

src = SRC.read_text(encoding="utf-8")
lines = src.split("\n")


def index_of(text, start=0):
    hits = [i for i, l in enumerate(lines) if l.strip() == text and i >= start]
    if len(hits) != 1:
        raise SystemExit(f"port.py: expected exactly one line {text!r} in main.tex, got {len(hits)}")
    return hits[0]


# Pieces of the LIPIcs source, located by their delimiting lines.
i_lst_begin = index_of(r"\lstdefinelanguage{lean}{")
i_bibstyle = index_of(r"\bibliographystyle{plainurl}")
listings_setup = lines[i_lst_begin:i_bibstyle]            # \lstdefinelanguage ... \lstset{...}

i_abs_begin = index_of(r"\begin{abstract}")
i_abs_end = index_of(r"\end{abstract}")
abstract_body = lines[i_abs_begin + 1:i_abs_end]

i_intro_rule = i_abs_end + 2                               # the %---- rule before \section{Introduction}
if not lines[i_abs_end + 1] == "" or not lines[i_intro_rule].startswith("%----"):
    raise SystemExit("port.py: unexpected text between the abstract and the Introduction")

i_genai = index_of(r"\section*{Use of generative AI}")
i_bib = index_of(r"\bibliography{../docs/paper-refs,extra}")
i_appendix = index_of(r"\appendix")
i_end = index_of(r"\end{document}")

body_main = lines[i_intro_rule:i_genai]                    # Introduction .. Conclusion
genai = lines[i_genai:i_bib]                               # "Use of generative AI" section
# Drop the trailing %---- rule before \bibliography; it is re-added below.
while genai and (genai[-1] == "" or genai[-1].startswith("%----")):
    genai.pop()
appendix_body = lines[i_appendix + 1:i_end]                # the two appendices
while appendix_body and appendix_body[-1] == "":
    appendix_body.pop()

# Layout fix: sn-jnl's text block is narrower than LIPIcs', so the six columns of
# Table 2 (fractions of \textwidth plus 12 \tabcolsep) overflow by 1.3pt; narrow the column
# separation of that one table.
TAB2 = r"\begin{tabular}{L{0.11\textwidth}L{0.13\textwidth}L{0.12\textwidth}L{0.15\textwidth}L{0.16\textwidth}L{0.14\textwidth}}"
hits = [i for i, l in enumerate(body_main) if l == TAB2]
if len(hits) != 1:
    raise SystemExit("port.py: Table 2's tabular line not found exactly once")
body_main.insert(hits[0], r"\setlength{\tabcolsep}{5pt}% layout only (FIDELITY.md)")

# The LIPIcs comment above the GenAI statement refers to Dagstuhl's policy; replace the comment
# lines only (they do not print).
genai_text = [l for l in genai if not l.startswith("%")]

abstract_text = "\n".join(abstract_body)
if "\n\n" in abstract_text:
    raise SystemExit("port.py: the abstract has a paragraph break, which \\abstract{} cannot hold")

PREAMBLE = r"""% Paper D, Journal of Automated Reasoning version. GENERATED by port.py from ../main.tex (the
% LIPIcs draft): edit ../main.tex and rerun `python3 port.py`, or, once the two versions are
% meant to diverge, edit this file and stop using port.py. FIDELITY.md lists every difference
% between the two PDFs.
%
% Template: Springer Nature LaTeX authoring template (sn-jnl.cls, December 2024 package),
% reference style sn-mathphys-num (Math and Physical Sciences, numbered), chosen because the
% LIPIcs draft uses numbered citations; JAR's own instructions could not be read (login wall),
% so the style is [AUTHOR TO APPROVE].
%
% Open before submission: every [AUTHOR TO APPROVE] placeholder in the Declarations, and the
% open items listed at the top of ../main.tex.

\documentclass[pdflatex,sn-mathphys-num]{sn-jnl}

\usepackage{amsmath,amssymb,amsfonts}
\usepackage{amsthm}
\usepackage{listings}
\usepackage{array}
\usepackage[capitalise,noabbrev]{cleveref}
\newcolumntype{L}[1]{>{\raggedright\arraybackslash}p{#1}}

% Theorem environments: one shared counter, as in the LIPIcs version (Definition 1, Theorem 2).
\theoremstyle{thmstyleone}
\newtheorem{theorem}{Theorem}
\theoremstyle{thmstylethree}
\newtheorem{definition}[theorem]{Definition}
\crefname{definition}{Definition}{Definitions}
\newcommand{\crefrangeconjunction}{--}% "Sections 4--7", as in the LIPIcs version

% sn-jnl's \subparagraph is a run-in heading, which a listing that follows at once would
% swallow; print the pending heading before the listing (layout only).
\makeatletter
\AddToHook{env/lstlisting/before}{\if@noskipsec\leavevmode\fi}
\makeatother

% Appendices are referred to as "Appendix A", as in the LIPIcs version.
\AtBeginEnvironment{appendices}{\crefalias{section}{appendix}}

"""

FRONT = r"""
\raggedbottom

\begin{document}

\title[Machine-Checked Complexity of Decision-Table Completeness]{Machine-Checked Complexity of Decision-Table Completeness in Lean}

\author*[1]{\fnm{Carlos A.} \sur{Russell}}\email{carlos.a.russell@gmail.com}
% ORCID, as in the LIPIcs version: https://orcid.org/0009-0003-3741-0230
% (sn-jnl prints no ORCID; Springer collects it in the submission system.)

\affil*[1]{\orgname{Independent Researcher}, \orgaddress{\city{Buenos Aires}, \country{Argentina}}}

\abstract{%
""" + abstract_text + r"""}

\keywords{decision tables, completeness, coNP-completeness, \#P-completeness, Lean 4,
  Cook--Levin theorem}

% LIPIcs ACM 2012 classification, kept for the submission form:
%   Theory of computation~Problems, reductions and completeness (500);
%   Theory of computation~Logic and verification (300).

\maketitle

"""

BACK = r"""
%-----------------------------------------------------------------------------------------------
\backmatter

\bmhead{Supplementary information}
The Lean development, latc-complexity.
% TODO (from the LIPIcs draft): archive with a DOI at submission (Zenodo), or an anonymous
% mirror for review.

\section*{Declarations}
% Headings from the Springer Nature template's Declarations list. Every statement is a
% placeholder for the author: the LIPIcs draft states none of them except the generative-AI
% disclosure and the artifact, from which the prefilled text is taken.

\bmhead{Funding}
[AUTHOR TO APPROVE: the LIPIcs draft has no funding statement.]

\bmhead{Competing interests}
[AUTHOR TO APPROVE: the LIPIcs draft has no competing-interests statement.]

\bmhead{Ethics approval and consent to participate}
[AUTHOR TO APPROVE: Not applicable.]

\bmhead{Consent for publication}
[AUTHOR TO APPROVE: Not applicable.]

\bmhead{Data availability}
[AUTHOR TO APPROVE: Not applicable.]

\bmhead{Materials availability}
[AUTHOR TO APPROVE: Not applicable.]

\bmhead{Code availability}
The Lean development, latc-complexity, described in \Cref{app:artifact}.
[AUTHOR TO APPROVE: repository URL and archive DOI (Zenodo), or an anonymous mirror for review.]

\bmhead{Author contribution}
[AUTHOR TO APPROVE: the paper has a single author; the LIPIcs draft has no contribution statement.]

\bmhead{Use of generative AI}
See the section ``Use of generative AI'' above. [AUTHOR TO APPROVE: its bracketed parts, and
whether JAR wants this statement in the Declarations, in the Methods or elsewhere.]

%-----------------------------------------------------------------------------------------------
\begin{appendices}
"""

GENAI_COMMENT = [
    "% The text below is the LIPIcs draft's statement, unchanged. The bracketed parts are the",
    "% author's to write and must be true; the references must be verified by the author",
    "% personally. Springer Nature's AI policy asks authors to describe the use and confirm",
    "% accountability (springernature.com/gp/policies/editorial-policies/ai-manuscript-preparation).",
]

out = []
out += PREAMBLE.rstrip("\n").split("\n")
out.append("")
out += listings_setup
out += FRONT.rstrip("\n").split("\n")
out.append("")
out += body_main
out += [genai[0]] + GENAI_COMMENT + genai_text[1:]
out += BACK.rstrip("\n").split("\n")
out += appendix_body
out += [
    "",
    r"\end{appendices}",
    "",
    "%-----------------------------------------------------------------------------------------------",
    r"\bibliography{../../docs/paper-refs,../extra}",
    "",
    r"\end{document}",
    "",
]

OUT.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {OUT}")
